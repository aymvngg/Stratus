using System.Text;
using System.Text.Json;
using Stratus.Core.Models;

namespace Stratus.Core.Services;

public static class DocGenerator
{
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
    };

    public static string BuildMarkdown(IEnumerable<Tweak> tweaks)
    {
        var ordered = Order(tweaks);
        var categories = ordered.Select(t => t.Category).Distinct().Count();

        var sb = new StringBuilder();
        sb.Append("# Tweak reference\n\n");
        sb.Append("Generated by `stratus docgen` from the compiled tweak catalog. Do not edit this file by hand.\n\n");
        sb.Append(ordered.Count).Append(" tweaks in ").Append(categories).Append(" categories.\n");

        foreach (var group in ordered.GroupBy(t => t.Category))
        {
            sb.Append("\n## ").Append(group.Key).Append('\n');
            foreach (var tweak in group)
            {
                sb.Append("\n### ").Append(tweak.Id).Append("\n\n");
                sb.Append("**").Append(tweak.Name).Append("** (Risk: ").Append(tweak.Risk)
                    .Append(", weight ").Append(tweak.Weight).Append(')');
                if (tweak.RequiresReboot)
                    sb.Append(" (needs a restart)");
                sb.Append("\n\n");
                sb.Append(OneLine(tweak.Description)).Append('\n');
            }
        }

        return sb.ToString();
    }

    public static string BuildJson(IEnumerable<Tweak> tweaks)
    {
        var entries = Order(tweaks)
            .Select(t => new DocEntry(
                t.Id,
                t.Name,
                t.Description,
                t.Category.ToString(),
                t.Risk.ToString(),
                t.Weight,
                t.RequiresReboot))
            .ToArray();

        return JsonSerializer.Serialize(entries, JsonOptions);
    }

    private static List<Tweak> Order(IEnumerable<Tweak> tweaks) => tweaks
        .OrderBy(t => (int)t.Category)
        .ThenBy(t => t.Name, StringComparer.OrdinalIgnoreCase)
        .ThenBy(t => t.Id, StringComparer.OrdinalIgnoreCase)
        .ToList();

    private static string OneLine(string text) => text.Contains('\n') || text.Contains('\r')
        ? string.Join(' ', text.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries))
        : text;

    private sealed record DocEntry(
        string Id,
        string Name,
        string Description,
        string Category,
        string Risk,
        int Weight,
        bool RequiresReboot);
}
